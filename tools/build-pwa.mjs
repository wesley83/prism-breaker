import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath, pathToFileURL} from 'node:url';

const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const hash = data => createHash('sha256').update(data).digest('hex');
const markerPattern = /<meta\b(?=[^>]*\bname=["']prism-release["'])[^>]*>/i;
const marker = version => '<meta name="prism-release" content="' + version + '">';
const excluded = new Set(['sw.js', 'pwa-release.js', 'scores.html', 'worlds.html']);

async function filesIn(directory) {
  const files = [];
  for (const entry of await fs.readdir(directory, {withFileTypes: true})) {
    const location = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await filesIn(location));
    else if (entry.isFile()) files.push(location);
    else throw new Error('Unexpected non-file in public: ' + location);
  }
  return files.sort();
}

export async function buildPwa({check = false, root = project} = {}) {
  const publicRoot = path.join(root, 'public');
  const template = await fs.readFile(path.join(root, 'tools/service-worker.template.js'), 'utf8');
  const files = (await filesIn(publicRoot)).filter(file => !excluded.has(path.relative(publicRoot, file).split(path.sep).join('/')));
  const assets = [];
  let normalizedIndex;
  for (const file of files) {
    const name = '/' + path.relative(publicRoot, file).split(path.sep).join('/');
    let data = await fs.readFile(file);
    if (name === '/index.html') {
      const html = data.toString('utf8');
      normalizedIndex = markerPattern.test(html) ? html.replace(markerPattern, marker('__PRISM_RELEASE__')) : html.replace(/<head>/i, '<head>\n ' + marker('__PRISM_RELEASE__'));
      if (!normalizedIndex.includes(marker('__PRISM_RELEASE__'))) throw new Error('index.html has no head element for its release marker');
      data = Buffer.from(normalizedIndex);
    }
    assets.push({path: name, sha256: hash(data), bytes: data.length});
  }
  if (!normalizedIndex) throw new Error('No index.html in the game assets');
  assets.sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0);
  // Changing the worker itself must produce a distinct release/cache name too.
  const version = hash(JSON.stringify(assets) + '\n' + template).slice(0, 20);
  const index = normalizedIndex.replace(marker('__PRISM_RELEASE__'), marker(version));
  const releaseModule = '// Generated by tools/build-pwa.mjs.\nexport const PWA_RELEASE = ' + JSON.stringify(version) + ';\n';
  assets.find(asset => asset.path === '/index.html').sha256 = hash(index);
  assets.find(asset => asset.path === '/index.html').bytes = Buffer.byteLength(index);
  assets.push({path: '/pwa-release.js', sha256: hash(releaseModule), bytes: Buffer.byteLength(releaseModule)});
  assets.sort((a, b) => a.path.localeCompare(b.path, 'en'));
  const constants = 'const VERSION = ' + JSON.stringify(version) + ';\nconst PRECACHE = ' + JSON.stringify(assets, null, 2) + ';';
  const worker = template.replace('// __PWA_CONSTANTS__', constants);
  const outputs = [['index.html', index], ['pwa-release.js', releaseModule], ['sw.js', worker]];
  if (check) {
    for (const [name, expected] of outputs) {
      const actual = await fs.readFile(path.join(publicRoot, name), 'utf8').catch(() => '');
      if (actual !== expected) throw new Error('Stale PWA build (' + name + '). Run node tools/build-pwa.mjs after all runtime edits before deploying.');
    }
  } else {
    for (const [name, output] of outputs) await fs.writeFile(path.join(publicRoot, name), output);
  }
  return {version, assets: assets.length, bytes: assets.reduce((sum, asset) => sum + asset.bytes, 0), checked: check};
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try { console.log(JSON.stringify(await buildPwa({check: process.argv.includes('--check')}))); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
