import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {releaseBytes, writeReleasePackage} from './immutable-release.mjs';

const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const hash = data => createHash('sha256').update(data).digest('hex');
const markerPattern = /<meta\b(?=[^>]*\bname=["']prism-release["'])[^>]*>/i;
const marker = version => '<meta name="prism-release" content="' + version + '">';
// Mutable/composed authoring HTML is reserialized by Pagelove; offline gameplay uses the generated bundle.
const excluded = new Set(['sw.js', 'pwa-release.js', 'scores.html', 'worlds.html', 'world-catalog.html', 'editor.html', 'editor-template.html', 'editor-route.html', 'world-policy.html']);

async function filesIn(directory) {
  const files = [];
  for (const entry of await fs.readdir(directory, {withFileTypes: true})) {
    const location = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await filesIn(location));
    else if (entry.isFile()) files.push(location);
    else throw new Error('Unexpected non-file in public: ' + location);
  }
  return files.sort();
}

export async function buildPwa({check = false, root = project} = {}) {
  const publicRoot = path.join(root, 'public');
  const template = await fs.readFile(path.join(root, 'tools/service-worker.template.js'), 'utf8');
  const files = (await filesIn(publicRoot)).filter(file => {const name=path.relative(publicRoot,file).split(path.sep).join('/');return !excluded.has(name)&&!name.startsWith('worlds/');});
  const assets = [];
  let normalizedIndex;
  for (const file of files) {
    const name = '/' + path.relative(publicRoot, file).split(path.sep).join('/');
    let data = await fs.readFile(file);
    if (name === '/index.html') {
      const html = data.toString('utf8');
      normalizedIndex = markerPattern.test(html) ? html.replace(markerPattern, marker('__PRISM_RELEASE__')) : html.replace(/<head>/i, '<head>\n ' + marker('__PRISM_RELEASE__'));
      if (!normalizedIndex.includes(marker('__PRISM_RELEASE__'))) throw new Error('index.html has no head element for its release marker');
      data = Buffer.from(normalizedIndex);
    }
    assets.push({path: name, sha256: hash(data), bytes: data.length});
  }
  if (!normalizedIndex) throw new Error('No index.html in the game assets');
  assets.sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0);
  const names = (await filesIn(publicRoot)).map(file => path.relative(publicRoot, file).split(path.sep).join('/')).filter(name => !name.startsWith('worlds/') && !['sw.js', 'scores.html','pwa-release.js'].includes(name));
  const extras=[];
  for(const name of names.filter(name=>!assets.some(a=>a.path==='/'+name)))extras.push([name,hash(await fs.readFile(path.join(publicRoot,name)))]);
  // Changing the worker itself must produce a distinct release/cache name too.
  const packager = await fs.readFile(new URL('./immutable-release.mjs', import.meta.url), 'utf8');
  const builder = await fs.readFile(new URL('./build-pwa.mjs', import.meta.url), 'utf8');
  const version = hash(JSON.stringify(assets) + JSON.stringify(extras) + '\n' + template + '\n' + packager + '\n' + builder).slice(0, 20);
  const index = normalizedIndex.replace(marker('__PRISM_RELEASE__'), marker(version));
  const releaseModule = '// Generated by tools/build-pwa.mjs.\nexport const PWA_RELEASE = ' + JSON.stringify(version) + ';\n';
  assets.find(asset => asset.path === '/index.html').sha256 = hash(index);
  assets.find(asset => asset.path === '/index.html').bytes = Buffer.byteLength(index);
  assets.push({path: '/pwa-release.js', sha256: hash(releaseModule), bytes: Buffer.byteLength(releaseModule)});
  assets.sort((a, b) => a.path.localeCompare(b.path, 'en'));
  names.push('pwa-release.js');
  const entries = [];
  for (const name of names) {
    const bytes = name === 'index.html' ? Buffer.from(index) : name === 'pwa-release.js' ? Buffer.from(releaseModule) : await fs.readFile(path.join(publicRoot, name));
    entries.push([name, releaseBytes(bytes, name, version, names)]);
  }
  // A cold build may not have generated pwa-release.js on disk yet.
  if (!names.includes('pwa-release.js')) entries.push(['pwa-release.js', Buffer.from(releaseModule)]);
  // Only cache assets and the schema-free template live under immutable URLs.
  // Root-only schema documents must not be discovered twice by Pagelove.
  const packaged = await writeReleasePackage({root, version, entries,stagedNames:new Set([...assets.map(a=>a.path.slice(1)),'editor-template.html'])});
  for (const asset of assets) {
    const record = packaged.manifest.files.find(file => file.path === asset.path);
    if (!record) throw Error('Missing immutable asset: ' + asset.path);
    Object.assign(asset, {url: record.url, sha256: record.sha256, bytes: record.bytes});
  }
  const constants = 'const VERSION = ' + JSON.stringify(version) + ';\nconst PRECACHE = ' + JSON.stringify(assets, null, 2) + ';';
  const worker = template.replace('// __PWA_CONSTANTS__', constants);
  const workerFile = path.join(packaged.directory, 'service-worker.js');
  const oldWorker = await fs.readFile(workerFile, 'utf8').catch(e=>{if(e.code!=='ENOENT')throw e;return null;});
  if(oldWorker!==null&&oldWorker!==worker)throw Error('Immutable package worker collision');
  await fs.writeFile(workerFile, worker);
  packaged.manifest.worker = {path:'/service-worker.js',url:'/releases/'+version+'/service-worker.js',sha256:hash(worker),bytes:Buffer.byteLength(worker)};
  await fs.writeFile(path.join(packaged.directory,'release.json'),JSON.stringify(packaged.manifest,null,2)+'\n');
  const outputs = [['index.html', index], ['pwa-release.js', releaseModule], ['sw.js', worker]];
  if (check) {
    for (const [name, expected] of outputs) {
      const actual = await fs.readFile(path.join(publicRoot, name), 'utf8').catch(() => '');
      if (actual !== expected) throw new Error('Stale PWA build (' + name + '). Run bun tools/build-pwa.mjs after all runtime edits before deploying.');
    }
  } else {
    for (const [name, output] of outputs) await fs.writeFile(path.join(publicRoot, name), output);
  }
  return {version, assets: assets.length, bytes: assets.reduce((sum, asset) => sum + asset.bytes, 0), checked: check, package: packaged.directory};
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try { console.log(JSON.stringify(await buildPwa({check: process.argv.includes('--check')}))); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
